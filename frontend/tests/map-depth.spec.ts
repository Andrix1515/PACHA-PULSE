import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function accessible(page: Page) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(result.violations.map(({ id, nodes }) => ({ id, nodes: nodes.map((n) => n.target) }))).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function outline(page: Page) {
  await page.goto('/#field')
  await page.getByText('Field tools', { exact: true }).click()
  await page.getByLabel('Import field GeoJSON', { exact: true }).setInputFiles({ name: 'plot.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify({ type: 'Polygon', coordinates: [[[-75.2,-12.05],[-75.199,-12.05],[-75.1988,-12.049],[-75.1995,-12.0488],[-75.2,-12.05]]] })) })
  await page.getByRole('button', { name: 'Close and save field', exact: true }).click()
  await page.getByText('Field tools', { exact: true }).click()
}

test('country search submits explicitly, moves the camera and never invents a field', async ({ page }) => {
  let calls = 0
  await page.route('**/api/v1/places/search?**', (route) => { calls++; return route.fulfill({ json: { results: [{ id: 'synthetic-peru', label: 'Peru', lat: -9, lon: -75, bounds: [[-18.4,-81.4],[-.02,-68.6]], kind: 'country', country_code: 'PE' }], source: 'Synthetic place transport fixture', retrieved_at: '2026-11-15', cached: false } }) })
  await page.goto('/#field')
  await page.getByRole('textbox', { name: 'Country or region', exact: true }).fill('Peru')
  expect(calls).toBe(0)
  await page.getByRole('button', { name: 'Search places', exact: true }).click()
  await expect(page.getByRole('list', { name: 'Place search results' })).toBeVisible()
  await accessible(page)
  await page.getByRole('list', { name: 'Place search results' }).getByRole('button').click()
  await expect(page.getByRole('status').filter({ hasText: 'Browsing Peru' }).first()).toBeVisible()
  expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('pacha-pulse.journey.v1')!).location)).toBeNull()
  await expect(page.getByRole('button', { name: 'Use this location', exact: true })).toBeDisabled()
  expect(calls).toBe(1)
})

test('search failure preserves manual controls and saved geometry', async ({ page }) => {
  await outline(page)
  const before = await page.evaluate(() => localStorage.getItem('pacha-pulse.parcel.v1'))
  await page.route('**/api/v1/places/search?**', (route) => route.fulfill({ status: 503, json: { error: { code: 'place_search_unavailable', message: 'Search unavailable. Use Field tools.' } } }))
  await page.getByRole('textbox', { name: 'Country or region' }).fill('Junin')
  await page.getByRole('button', { name: 'Search places' }).click()
  await expect(page.getByRole('alert')).toContainText('unavailable')
  await page.getByRole('button', { name: 'Dismiss search results' }).click()
  await page.getByText('Field tools', { exact: true }).click()
  await expect(page.getByLabel('Latitude', { exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('pacha-pulse.parcel.v1'))).toBe(before)
})

test('saved shape opens live 3D, camera and stage controls work, scale stays clear', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message))
  await outline(page)
  const scale = await page.locator('.leaflet-control-scale').boundingBox(), caption = await page.locator('.field-confirm-bar').boundingBox()
  expect(scale && caption && scale.y + scale.height <= caption.y).toBeTruthy()
  const before = await page.evaluate(() => localStorage.getItem('pacha-pulse.parcel.v1'))
  await page.getByRole('button', { name: 'Explore in 3D', exact: true }).click()
  await expect(page.locator('.field-canvas')).toHaveAttribute('data-renderer', 'webgl')
  await expect(page.getByRole('heading', { name: 'A little closer to your field.' })).toBeFocused()
  const canvas = page.locator('.field-canvas canvas'), image = await canvas.screenshot()
  await page.getByRole('button', { name: 'Rotate field right' }).click()
  expect(image.equals(await canvas.screenshot())).toBe(false)
  await page.getByRole('button', { name: 'Reset field camera' }).click()
  await page.getByRole('button', { name: 'Flowering', exact: true }).click()
  await expect(page.locator('.growth-timeline h2')).toContainText('Flowering')
  await page.getByRole('combobox', { name: 'Illustrate a crop' }).selectOption('bean')
  await expect(page.locator('.growth-timeline h2')).toContainText('Bean')
  await accessible(page)
  await page.screenshot({ path: `../docs/evidence/pacha-v2-3d-${info.project.name}.png`, fullPage: true })
  await page.getByText('What do we actually know?', { exact: true }).click()
  await expect(page.locator('.explorer-options')).toContainText('not measured')
  await page.getByRole('button', { name: 'Back to map', exact: true }).click()
  expect(await page.evaluate(() => localStorage.getItem('pacha-pulse.parcel.v1'))).toBe(before)
  expect(errors).toEqual([])
})

