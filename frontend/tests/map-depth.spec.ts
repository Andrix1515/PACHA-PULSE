test('Pacha travels between scenes in the same live canvas and respects pause', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  await expect(page.locator('.pacha-model')).toHaveAttribute('data-renderer', 'webgl')
  await page.locator('.pacha-model canvas').evaluate((el) => { el.dataset.identity = 'persistent-actor' })
  const before = await page.locator('.pacha-stage-character').boundingBox()
  await page.getByRole('button', { name: /I grow crops/ }).click()
  await expect(page.locator('.pacha-stage-character')).toHaveAttribute('data-travelling', 'true')
  await expect(page.locator('.pacha-model')).toHaveAttribute('data-mood', 'travel')
  await expect(page.locator('.pacha-stage-character')).toHaveAttribute('data-travelling', 'false')
  const after = await page.locator('.pacha-stage-character').boundingBox()
  expect(Math.hypot(after!.x - before!.x, after!.y - before!.y)).toBeGreaterThan(70)
  await expect(page.locator('.pacha-model canvas')).toHaveAttribute('data-identity', 'persistent-actor')
  await page.getByRole('button', { name: 'Pause animations', exact: true }).click()
  await expect(page.locator('.journey-shell')).toHaveClass(/motion-off/)
  await expect(page.locator('.pacha-stage-character')).toHaveAttribute('data-travelling', 'false')
})
