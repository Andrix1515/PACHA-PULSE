import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function addPoint(page: import('@playwright/test').Page, lat: string, lon: string) {
  await page.getByLabel('Latitud del vértice', { exact: true }).fill(lat)
  await page.getByLabel('Longitud del vértice', { exact: true }).fill(lon)
  await page.getByRole('button', { name: 'Añadir vértice', exact: true }).click()
}

test('dibujo por coordenadas, validación, persistencia y GeoJSON', async ({ page }, info) => {
  await page.goto('/#demo')
  await page.getByRole('button', { name: 'Dibujar o editar parcela' }).click()
  await page.getByLabel('Nombre del contorno').fill('Parcela de ensayo')
  await page.getByRole('button', { name: 'Cerrar y guardar parcela' }).click()
  await expect(page.getByRole('alert')).toContainText('3 y 100')
  await addPoint(page, '-12.05', '-75.2')
  await addPoint(page, '-12.05', '-75.199')
  await addPoint(page, '-12.049', '-75.199')
  await addPoint(page, '-12.049', '-75.2')
  await page.getByRole('button', { name: 'Cerrar y guardar parcela' }).click()
  await expect(page.getByLabel('Parcela guardada')).toContainText('4 vértices')
  await expect(page.getByLabel('Parcela guardada')).toContainText('aproximada')
  await expect(page.getByText('Ubicación seleccionada:', { exact: false })).toContainText('referencia de parcela')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar parcela GeoJSON' }).click()
  expect((await downloadEvent).suggestedFilename()).toBe('pacha-pulse-parcela.geojson')
  await page.getByRole('button', { name: 'Planificar Tu próxima campaña' }).click()
  await expect(page.getByLabel('Parcela guardada')).toContainText('Parcela de ensayo')
  await page.getByLabel('Modo de trabajo').selectOption('agronomist')
  await expect(page.getByText('Modo Agrónomo', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Parcela guardada')).toContainText('Parcela de ensayo')
  await page.getByRole('button', { name: 'Dibujar o editar parcela' }).click()
  await page.getByLabel('Latitud del punto 1', { exact: true }).fill('-12.0501')
  await page.getByRole('button', { name: 'Aplicar coordenadas del punto 1' }).click()
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(axe.violations.map(({ id, nodes }) => ({ id, targets: nodes.map((node) => node.target) }))).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: `../docs/evidence/pacha-parcel-${info.project.name}.png`, fullPage: true })
  await page.getByRole('button', { name: 'Cancelar cambios del contorno' }).click()
  await page.getByRole('button', { name: 'Eliminar parcela guardada' }).click()
  await expect(page.getByLabel('Parcela guardada')).toHaveCount(0)
  await page.getByRole('button', { name: 'Deshacer eliminación de parcela' }).click()
  await expect(page.getByLabel('Parcela guardada')).toContainText('Parcela de ensayo')
})

test('clics en mapa y alternativa de teclado sin arrastrar', async ({ page }) => {
  await page.goto('/#demo')
  await page.getByLabel('Latitud', { exact: true }).fill('-12.05')
  await page.getByLabel('Longitud', { exact: true }).fill('-75.2')
  await page.getByRole('button', { name: 'Usar ubicación' }).click()
  await page.getByRole('button', { name: 'Acercar al punto' }).click()
  await page.getByRole('button', { name: 'Dibujar o editar parcela' }).click()
  const map = page.locator('.leaflet-container')
  await map.click({ position: { x: 160, y: 130 } })
  await map.click({ position: { x: 260, y: 135 } })
  await map.click({ position: { x: 210, y: 235 } })
  await expect(page.getByLabel('Vértices editables del contorno').getByRole('listitem')).toHaveCount(3)
  await page.getByRole('button', { name: 'Quitar último punto' }).click()
  await map.focus()
  await page.keyboard.press('ArrowDown')
  await page.getByRole('button', { name: 'Añadir punto del centro del mapa' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Vértices editables del contorno').getByRole('listitem')).toHaveCount(3)
  await page.getByRole('button', { name: 'Cerrar y guardar parcela' }).click()
  await expect(page.getByLabel('Parcela guardada')).toBeVisible()
})

test('importación rechaza geometría inválida sin reemplazar la parcela', async ({ page }) => {
  await page.goto('/#demo')
  const file = page.getByLabel('Importar parcela GeoJSON')
  await file.setInputFiles({ name: 'cruzado.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify({ type: 'Polygon', coordinates: [[[-75.2, -12.05], [-75.199, -12.049], [-75.199, -12.05], [-75.2, -12.049], [-75.2, -12.05]]] })) })
  await expect(page.getByRole('alert')).toContainText('cruzan')
  await file.setInputFiles({ name: 'valido.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify({ type: 'Feature', properties: { name: 'Importada' }, geometry: { type: 'Polygon', coordinates: [[[-75.2, -12.05], [-75.199, -12.05], [-75.199, -12.049], [-75.2, -12.05]]] } })) })
  await expect(page.getByLabel('Nombre del contorno')).toHaveValue('Importada')
  await expect(page.getByLabel('Parcela guardada')).toHaveCount(0)
  await page.getByRole('button', { name: 'Cerrar y guardar parcela' }).click()
  await expect(page.getByLabel('Parcela guardada')).toContainText('Importada')
})

