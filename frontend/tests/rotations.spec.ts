import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('tres secuencias, NASA compartida y escenario 70 %', async ({ page }, testInfo) => {
  await page.goto('/#demo')
  await page.getByRole('button', { name: 'Abrir ejemplo real:' }).click()
  await expect(page.getByLabel('Resultados de clima NASA POWER')).toBeVisible()
  await page.getByRole('button', { name: 'Planificar Tu próxima campaña' }).click()
  await page.getByLabel('Confirmo que la primera secuencia').check()
  await page.getByRole('button', { name: 'Comparar tres rotaciones' }).click()
  const result = page.getByLabel('Resultados de comparación de rotaciones')
  await expect(result).toBeVisible()
  await expect(result).toContainText('60.6 mm')
  await expect(result.getByRole('row')).toHaveCount(4)
  await page.getByRole('button', { name: '70 % · más seco' }).click()
  await expect(result).toHaveCount(0)
  await page.getByRole('button', { name: 'Comparar tres rotaciones' }).click()
  await expect(result).toContainText('42.5 mm')
  await expect(result).toContainText('Hipótesis')
  await expect(result).toContainText('Faltan ETo y Kc')
  await page.getByRole('button', { name: 'Monitorear Tus cultivos, hoy' }).click()
  await page.getByRole('button', { name: 'Planificar Tu próxima campaña' }).click()
  await expect(result).toContainText('42.5 mm')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(axe.violations.map(({ id, nodes }) => ({ id, targets: nodes.map((node) => node.target) }))).toEqual([])
  await page.screenshot({ path: `../docs/evidence/comparison-${testInfo.project.name}.png`, fullPage: true })
})

test('editar rotaciones invalida resultados sin inventar agua o rendimiento', async ({ page }) => {
  await page.goto('/#demo')
  await page.getByRole('button', { name: 'Planificar Tu próxima campaña' }).click()
  await page.getByLabel('Habitual / referencia, campaña 2').selectOption('wheat')
  await page.getByRole('button', { name: 'Comparar tres rotaciones' }).click()
  const result = page.getByLabel('Resultados de comparación de rotaciones')
  await expect(result).toContainText('Sin datos climáticos completos')
  await expect(result).toContainText('todavía no fue confirmada')
  await expect(result).toContainText('rentabilidad no disponibles')
  await page.getByLabel('Alternativa A, campaña 3').selectOption('fallow')
  await expect(result).toHaveCount(0)
})
