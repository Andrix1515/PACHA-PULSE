import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('arranque real, proxy API, mapa y diseño sin desbordamiento', async ({ page, request }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const health = await request.get('/api/v1/health')
  expect(health.status()).toBe(200)
  expect(await health.json()).toEqual({ status: 'ok', service: 'agroshift-api', version: '0.1.0' })
  await page.goto('/#demo')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Conoce mejor tu campo.')
  await expect(page.getByText('API local conectada')).toBeVisible()
  await expect(page.getByText('No disponible', { exact: true })).toHaveCount(3)
  await expect(page.getByRole('link', { name: 'OpenStreetMap', exact: true })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Mapa mundial para seleccionar una ubicación' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  // La tesela real es una comprobación aparte: el servicio público puede fallar.
  await page.waitForTimeout(1200)
  const loadedTiles = await page.locator('.leaflet-tile-loaded').count()
  await testInfo.attach('estado-teselas-reales', { body: `Teselas cargadas desde OSM: ${loadedTiles}`, contentType: 'text/plain' })
  await page.screenshot({ path: `../docs/evidence/demo-${testInfo.project.name}.png`, fullPage: true })
  expect(errors).toEqual([])
})

test('coordenadas válidas, límites y contexto entre recorridos', async ({ page }) => {
  await page.goto('/#demo')
  const lat = page.getByLabel('Latitud', { exact: true })
  const lon = page.getByLabel('Longitud', { exact: true })
  const submit = page.getByRole('button', { name: 'Usar ubicación' })
  await submit.click()
  await expect(page.getByRole('alert')).toContainText('Ingresa una latitud')
  await lat.fill('91')
  await lon.fill('0')
  await submit.click()
  await expect(page.getByRole('alert')).toBeVisible()
  await lat.fill('-12,0464')
  await lon.fill('-77,0428')
  await submit.click()
  await expect(page.getByText('Ubicación seleccionada:', { exact: false })).toContainText('-12.0464°, -77.0428°')
  await page.getByRole('button', { name: 'Planificar Tu próxima campaña' }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Dale perspectiva al futuro.')
  await expect(page.getByLabel('Contexto compartido de planificación')).toContainText('-12.0464°, -77.0428°')
  await lat.fill('48.85')
  await lon.fill('2.35')
  await submit.click()
  await expect(page.getByLabel('Contexto compartido de planificación')).toContainText('48.8500°, 2.3500°')
  await lat.fill('90')
  await lon.fill('180')
  await submit.click()
  await expect(page.getByText('Esta proyección', { exact: false })).toBeVisible()
  await lat.fill('0')
  await lon.fill('0')
  await submit.click()
  await expect(page.getByLabel('Contexto compartido de planificación')).toContainText('0.0000°, 0.0000°')
  await lon.fill('181')
  await submit.click()
  await expect(page.getByRole('alert')).toBeVisible()
})

