import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function accessible(page: Page) {
  const result = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']).analyze()
  expect(result.violations.map(({ id, nodes }) => ({ id, targets: nodes.map((node) => node.target) }))).toEqual([])
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}
async function tools(page: Page) { await page.getByText('Field tools', { exact: true }).click() }
async function point(page: Page, lat = '-12.05', lon = '-75.2') {
  await page.getByLabel('Latitude', { exact: true }).fill(lat)
  await page.getByLabel('Longitude', { exact: true }).fill(lon)
  await page.getByRole('button', { name: 'Use location', exact: true }).click()
}
async function navigate(page: Page, name: string) {
  await page.getByRole('button', { name: 'Open journey menu' }).click()
  await page.getByRole('navigation', { name: 'Main navigation' }).getByRole('button', { name, exact: true }).click()
}

