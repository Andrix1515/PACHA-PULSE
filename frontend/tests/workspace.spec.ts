test('invalid GeoJSON does not replace data and valid import remains a draft', async ({ page }) => {
  await page.goto('/#field')
  const file = page.getByLabel('Import field GeoJSON', { exact: true })
  await file.setInputFiles({ name: 'crossed.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify({ type: 'Polygon', coordinates: [[[-75.2, -12.05], [-75.199, -12.049], [-75.199, -12.05], [-75.2, -12.049], [-75.2, -12.05]]] })) })
  await expect(page.getByRole('alert')).toContainText('cross')
  await file.setInputFiles({ name: 'valid.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify({ type: 'Feature', properties: { name: 'Imported field' }, geometry: { type: 'Polygon', coordinates: [[[-75.2, -12.05], [-75.199, -12.05], [-75.199, -12.049], [-75.2, -12.05]]] } })) })
  await expect(page.getByLabel('Outline name', { exact: true })).toHaveValue('Imported field')
  await expect(page.getByLabel('Saved field', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Close and save field', exact: true }).click()
  await expect(page.getByLabel('Saved field', { exact: true })).toContainText('Imported field')
})

