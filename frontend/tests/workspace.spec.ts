test('teclado y accesibilidad automatizada de ambos recorridos', async ({ page }) => {
  await page.goto('/#demo')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Saltar al contenido' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('main')).toBeFocused()
  const lat = page.getByLabel('Latitud', { exact: true })
  await lat.focus()
  await page.keyboard.type('-33.4')
  await page.keyboard.press('Tab')
  await expect(page.getByLabel('Longitud', { exact: true })).toBeFocused()
  await page.keyboard.type('-70.6')
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Usar ubicación' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByText('Ubicación seleccionada:', { exact: false })).toContainText('-33.4000°, -70.6000°')
  const monitoring = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(monitoring.violations.map(({ id, nodes }) => ({ id, targets: nodes.map((node) => node.target) }))).toEqual([])
  await page.getByRole('button', { name: 'Ir a Planificar' }).click()
  await page.getByLabel('Modo de trabajo').selectOption('agronomist')
  const planning = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(planning.violations.map(({ id, nodes }) => ({ id, targets: nodes.map((node) => node.target) }))).toEqual([])
})

test('error del servidor y respuesta inesperada permiten reintentar', async ({ page }) => {
  // Mock explícito de fallo de API; el reintento final consulta FastAPI real.
  await page.route('**/api/v1/health', (route) => route.fulfill({ status: 500, contentType: 'application/json', body: '{"error":{"code":"internal_error"}}' }))
  await page.goto('/#demo')
  await expect(page.getByText('API local sin conexión')).toBeVisible()
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
  await page.unroute('**/api/v1/health')
  await page.route('**/api/v1/health', (route) => route.fulfill({ json: { status: 'ok', service: 'otra-api' } }))
  await page.getByRole('button', { name: 'Reintentar conexión con la API' }).click()
  await expect(page.getByText('API local sin conexión')).toBeVisible()
  await page.unroute('**/api/v1/health')
  await page.getByRole('button', { name: 'Reintentar conexión con la API' }).click()
  await expect(page.getByText('API local conectada')).toBeVisible()
})

test('red cartográfica caída permite coordenadas y selección en mapa', async ({ page }) => {
  // Mock explícito de red caída para teselas; no se simulan observaciones NASA.
  await page.route('https://tile.openstreetmap.org/**', (route) => route.abort('failed'))
  await page.goto('/#demo')
  await expect(page.getByText('No se pudo cargar parte del mapa.', { exact: false })).toBeVisible()
  await page.getByLabel('Latitud', { exact: true }).fill('10')
  await page.getByLabel('Longitud', { exact: true }).fill('20')
  await page.getByRole('button', { name: 'Usar ubicación' }).click()
  await expect(page.getByText('Ubicación seleccionada:', { exact: false })).toContainText('10.0000°, 20.0000°')
  await page.locator('.leaflet-container').click({ position: { x: 150, y: 140 } })
  await expect(page.getByText('Ubicación seleccionada:', { exact: false })).toContainText('mapa')
  await expect(page.getByLabel('Latitud', { exact: true })).not.toHaveValue('10')
})
