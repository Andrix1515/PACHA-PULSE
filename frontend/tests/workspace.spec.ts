test('polygon import stays draft, saved polygon persists and can be deleted or restored', async ({ page }) => {
  await page.goto('/#field'); await tools(page)
  const file = page.getByLabel('Import field GeoJSON', { exact: true })
  await file.setInputFiles({ name: 'bad.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify({ type: 'Polygon', coordinates: [[[-75.2,-12.05],[-75.199,-12.049],[-75.199,-12.05],[-75.2,-12.049],[-75.2,-12.05]]] })) })
  await expect(page.getByRole('alert')).toContainText('cross')
  await file.setInputFiles({ name: 'field.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify({ type: 'Feature', properties: { name: 'My outline' }, geometry: { type: 'Polygon', coordinates: [[[-75.2,-12.05],[-75.199,-12.05],[-75.199,-12.049],[-75.2,-12.05]]] } })) })
  await expect(page.getByLabel('Saved field', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Close and save field', exact: true }).click()
  await expect(page.getByLabel('Saved field', { exact: true })).toContainText('3 vertices')
  await point(page, '10', '20')
  await expect(page.locator('.field-confirm-bar')).toContainText('Weather point outside outline')
  await page.getByRole('button', { name: 'Use field query point', exact: true }).click()
  await expect(page.locator('.field-confirm-bar')).not.toContainText('Weather point outside outline')
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export field GeoJSON' }).click()
  expect((await download).suggestedFilename()).toMatch(/geojson$/)
  await page.reload(); await tools(page)
  await expect(page.getByLabel('Saved field', { exact: true })).toContainText('My outline')
  await page.getByRole('button', { name: 'Delete saved field', exact: true }).click()
  await expect(page.getByLabel('Saved field', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Undo field deletion', exact: true }).click()
  await expect(page.getByLabel('Saved field', { exact: true })).toBeVisible()
  await accessible(page)
})

